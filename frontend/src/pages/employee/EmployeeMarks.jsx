import { useCallback, useEffect, useMemo, useState } from 'react';
import {
  ClipboardList, FileSpreadsheet, Lock, History, Save, Download, Users, Clock, ShieldAlert,
} from 'lucide-react';
import Modal from '../../components/Modal';
import ClassSelect from '../../components/ClassSelect';
import { useAuth } from '../../context/AuthContext';
import api from '../../services/api';
import LoadErrorState from '../../components/LoadErrorState';
import { useLoadState } from '../../utils/useLoadState';
import toast from '../../services/toast';
import { useSubmitGuard } from '../../utils/useSubmitGuard';
import { useNow } from '../../utils/useNow';
import { useLatestRequest } from '../../utils/useLatestRequest';
import { shortStamp } from '../../utils/date';
import {
  editRemainingMs,
  formatEditRemaining,
  shortEditRemaining,
  parseObtained,
  EDIT_LOCKED_LABEL,
  MARKS_MAX,
} from '../../utils/marks';

/**
 * The bulk-upload header, in the exact order the server requires. It has NO
 * Class and NO Subject column on purpose: both are already fixed by the
 * selectors above, and a file that could name its own class or subject is a
 * file that could contradict the page — or target a subject this teacher does
 * not teach. Kept here only for the help text; the template the teacher
 * downloads is generated by the same parser that reads it back.
 */
const BULK_COLUMNS = [
  'RollNumber', 'StudentName', 'ExamName', 'ExamDate', 'MaxMarks', 'ObtainedMarks',
];

/**
 * Turn a server error map into readable lines. The bulk routes answer with
 * `{ file, row_3: { RollNumber: '…' }, entry_2: { obtained: '…' } }`, so a
 * nested object becomes "Row 3 — RollNumber: …".
 */
const errorLines = (errors) =>
  Object.entries(errors || {}).map(([field, detail]) => {
    const label = field === 'file' ? 'File' : field.startsWith('row_') ? `Row ${field.slice(4)}` : field;
    const text = typeof detail === 'string'
      ? detail
      : Object.entries(detail || {}).map(([col, msg]) => `${col}: ${msg}`).join(' · ');
    return `${label} — ${text}`;
  });

/** "Nursery A · Mathematics" — the label on a teaching-assignment chip. Uses the
 *  class's display name, so a named level reads correctly and nothing here
 *  rebuilds a name out of the level order. */
const chipLabel = (a) => `${a.classLabel || a.classId} · ${a.subject}`;

/** Assignments in the order a teacher reads best: level order, then section, then subject. */
const sortPairs = (list) => [...list].sort(
  (a, b) => ((a.order ?? Number(a.grade)) - (b.order ?? Number(b.grade)))
    || a.section.localeCompare(b.section)
    || a.subject.localeCompare(b.subject),
);

/**
 * Employee Portal — Marks Entry.
 *
 * This writes the SAME Exam / MarksEntry records the admin panel's Marks Entry
 * writes; there is no separate teacher-only store, so a mark a teacher enters is
 * immediately visible in the admin's Saved Marks table, the student profile and
 * the Student Portal.
 *
 * What makes it a *teacher's* page is the scope: the (class, subject) pairs come
 * from GET /employees/:id/marks/assignments, which derives them live from the
 * TIMETABLE. The dropdowns below only ever offer those pairs, but that is a
 * convenience, not the control — the write endpoints re-derive the same list and
 * reject anything outside it with 403, so a hand-rolled request cannot enter
 * marks for a subject somebody else teaches.
 *
 * ── The 48-hour edit window ────────────────────────────────────────────────
 * Marks a teacher saves stay correctable by that teacher for two days; after
 * that only the Admin Panel can change them. Three things on this page are
 * consequences of that, and all three read the same two real values — the
 * batch's `savedAt` from the server and the current time from `useNow`:
 *
 *   - the inputs are disabled and the note explains why, once the window closes;
 *   - the "already saved" cards show the time left, or "Locked";
 *   - the confirmation after a save counts the window down from the instant the
 *     server actually stamped, so it is right immediately and still right after
 *     a reload.
 *
 * Nothing here grants or refuses a save. The server refuses a closed window with
 * 403 EDIT_LOCKED, and that is the control; the disabled inputs and the badges
 * exist so the teacher finds out before they press Save, not so they are stopped.
 */
export default function EmployeeMarks() {
  const { user } = useAuth();
  const employeeId = user?.linkedEntityId;
  // The single reading of "now" every countdown on this page is derived from.
  const now = useNow(30000);

  /* ---- server data ---- */
  const [assignments, setAssignments] = useState([]);
  const { loading, setLoading, error, reloadKey, retry, fail } = useLoadState();
  const [grid, setGrid] = useState(null);
  const [gridLoading, setGridLoading] = useState(false);

  /* ---- selection ---- */
  const [classId, setClassId] = useState('');
  const [subject, setSubject] = useState('');

  /* ---- the exam being entered ---- */
  const [examName, setExamName] = useState('');
  const [date, setDate] = useState('');
  const [maxMarks, setMaxMarks] = useState('100');
  const [loadedExamName, setLoadedExamName] = useState('');
  // { [studentId]: raw input text } — kept as text so a half-typed "1" is not
  // rewritten to a number under the cursor.
  const [entries, setEntries] = useState({});

  const [saving, setSaving] = useState(false);
  const [confirmation, setConfirmation] = useState(null);

  const [bulkOpen, setBulkOpen] = useState(false);
  const [bulkBusy, setBulkBusy] = useState(false);
  const [bulkErrors, setBulkErrors] = useState([]);
  const [downloading, setDownloading] = useState('');

  const [guard, cooling] = useSubmitGuard();

  /* ---- the class list is the teacher's own, never the school's ---- */
  const classChoices = useMemo(() => {
    const seen = new Map();
    sortPairs(assignments).forEach((a) => {
      if (!seen.has(a.classId)) seen.set(a.classId, { id: a.classId, label: a.classLabel });
    });
    return [...seen.values()];
  }, [assignments]);

  const subjectsForClass = useMemo(
    () => assignments.filter((a) => a.classId === classId).map((a) => a.subject),
    [assignments, classId],
  );
  const activeClass = classChoices.find((c) => c.id === classId) || null;
  const activeAssignment = assignments.find((a) => a.classId === classId && a.subject === subject) || null;
  /** The class's display name for the confirmations — the shared `classLabel`
   *  the server already sent, never rebuilt here from the grade. */
  const chipClassLabel = activeAssignment ? (activeAssignment.classLabel || activeClass?.label || '') : '';

  /**
   * Read the roster for one (class, subject) pair, plus the exams already saved
   * against it. `examToLoad` (a saved exam's name) additionally pulls that
   * exam's details and marks into the form, which is what turns a correction
   * into an edit instead of a second set of rows.
   *
   * The pair is passed in rather than read from state: the caller knows which
   * pair it is switching to, and a state read here would still hold the
   * PREVIOUS pair on the render that changes it.
   *
   * Two of these can be in flight at once — the page opens on the first
   * assignment by itself, and a click on a chip or a saved card starts another
   * load before the first has come back. Whichever response arrived last used to
   * win outright, and the mixture was not merely a flicker: the pair-wide load
   * carries no open exam, so a stale one landing after a card's load left the
   * grid reporting no exam while the card's marks were already in the form. With
   * the edit window that is worse than cosmetic — the batch reads as having no
   * window at all, so a LOCKED exam would show live, editable inputs and a Save
   * button that the server would then refuse. So each load takes a number and
   * only the newest is allowed to write; the ones it superseded are discarded.
   */
  const gridLoad = useLatestRequest();
  const loadGrid = useCallback(
    (pairClassId, pairSubject, examToLoad) => {
      if (!pairClassId || !pairSubject) return Promise.resolve(null);
      const request = gridLoad.next();
      setGridLoading(true);
      const params = { classId: pairClassId, subject: pairSubject };
      if (examToLoad) params.examName = examToLoad;
      return api.get(`/employees/${employeeId}/marks?${new URLSearchParams(params)}`)
        .then((r) => {
          const data = r.data.data;
          // Superseded while in flight: a newer load is already the truth.
          if (!gridLoad.isLatest(request)) return null;
          setGrid(data);
          if (examToLoad && data.exam) {
            setExamName(data.exam.examName);
            setDate(data.exam.date || '');
            if (data.exam.maxMarks) setMaxMarks(String(data.exam.maxMarks));
            setEntries(
              Object.fromEntries(
                data.roster
                  .filter((row) => row.obtained !== null && row.obtained !== undefined)
                  .map((row) => [row.studentId, String(row.obtained)]),
              ),
            );
            setLoadedExamName(data.exam.examName);
          }
          return data;
        })
        // Gated exactly like the success and finally paths above: a superseded
        // request must not be able to raise the page's error state after a
        // newer one has already answered, or the block stays up over live data.
        .catch((err) => { if (gridLoad.isLatest(request)) fail(err); })
        .finally(() => { if (gridLoad.isLatest(request)) setGridLoading(false); });
    },
    [employeeId, gridLoad, fail],
  );

  /**
   * Choose the (class, subject) pair to work on, clearing whatever the previous
   * pair had in the form.
   *
   * The reset lives in the handler rather than in an effect keyed on the pair,
   * because a mark belongs to exactly one pair: an effect would let the previous
   * subject's numbers survive a render under the new subject's name, and a
   * double-click could even have them saved against the new subject. Resetting
   * in the same update that moves the pair makes that unreachable.
   */
  const selectPair = useCallback((nextClassId, nextSubject) => {
    setClassId(nextClassId);
    setSubject(nextSubject);
    setGrid(null);
    setEntries({});
    setExamName('');
    setDate('');
    setMaxMarks('100');
    setLoadedExamName('');
    setConfirmation(null);
    loadGrid(nextClassId, nextSubject, '');
  }, [loadGrid]);

  /**
   * Switching class keeps the teacher's subject when that class also has them
   * for it, and otherwise falls to the new class's first subject — a class can
   * never be left showing a subject this teacher does not hold there.
   */
  const selectClass = (nextClassId) => {
    const keep = assignments.find((a) => a.classId === nextClassId && a.subject === subject);
    const first = assignments.find((a) => a.classId === nextClassId);
    selectPair(nextClassId, (keep || first || {}).subject || '');
  };

  const loadAssignments = useCallback(
    () => api.get(`/employees/${employeeId}/marks/assignments`).then((r) => r.data.data || []),
    [employeeId],
  );

  useEffect(() => {
    if (!employeeId) return undefined;
    loadAssignments()
      .then((list) => {
        setAssignments(list);
        // Open on the first class, so the page arrives with a roster already
        // on screen instead of an empty dropdown waiting to be chosen.
        const first = sortPairs(list)[0];
        if (first) selectPair(first.classId, first.subject);
      })
      .catch(fail)
      .finally(() => setLoading(false));
    return undefined;
  }, [employeeId, loadAssignments, selectPair, reloadKey, fail, setLoading]);

  const setEntry = (studentId, value) => setEntries((prev) => ({ ...prev, [studentId]: value }));

  /* ---- live validation — every number is checked as it is typed ----
     The bounds mirror the server schema exactly (whole number, 1–10000), so a
     value that trips a rule here is caught before a round trip instead of
     coming back as a generic 400. The server still validates: this is
     feedback, not the control. */
  const maxValue = /^\d+$/.test(String(maxMarks).trim()) ? Number(maxMarks) : NaN;
  const maxMarksError = !String(maxMarks).trim()
    ? 'Max Marks is required'
    : Number.isNaN(maxValue) || maxValue < 1
      ? 'Max Marks must be a whole number of at least 1'
      : maxValue > MARKS_MAX
        ? `Max Marks cannot be more than ${MARKS_MAX}`
        : null;

  const roster = useMemo(() => grid?.roster || [], [grid]);
  const rowState = useMemo(
    () => Object.fromEntries(roster.map((r) => [r.studentId, parseObtained(entries[r.studentId], maxValue)])),
    [roster, entries, maxValue],
  );

  const enteredCount = roster.filter((r) => rowState[r.studentId]?.state === 'ok').length;
  const invalidRows = roster.filter((r) => rowState[r.studentId]?.state === 'invalid');
  const hasInvalid = invalidRows.length > 0;
  const examNameError = examName.trim().length < 2 ? 'Exam name is required' : null;
  const renamed = loadedExamName && examName.trim() && examName.trim() !== loadedExamName;

  /* ---- the loaded batch's edit window, recomputed on every tick ----
     `grid.exam.savedAt` is the server's own record of when this teacher last
     saved the batch now open in the grid — the same `savedAt` the save response
     hands back, and the same key the "already saved" cards use below. It is
     re-derived from `now` rather than read from the server's `locked` flag, so
     the inputs grey out at the exact moment the window closes without a refetch
     — and so a stale `locked` from a response that has been open a while cannot
     leave an editable-looking form. A batch with no `savedAt` (a fresh exam, or
     one only the office ever entered) has no window to close. */
  const savedAt = grid?.exam?.savedAt || null;
  const remainingMs = editRemainingMs(savedAt, now);
  const locked = remainingMs === 0;
  /** Everything in the form is frozen together — the exam identity included. */
  const readOnly = locked || saving;
  /* The window the just-closed dialog is counting, off the instant the SERVER
     stamped — so it cannot drift from the badge on the card behind it, and it
     keeps ticking while the dialog sits open. */
  const justSavedMs = editRemainingMs(confirmation?.savedAt, now);

  const canSave = Boolean(classId && subject) && enteredCount > 0 && !hasInvalid
    && !maxMarksError && !examNameError && !locked;

  /** Why Save is unavailable, in the teacher's words — the button's own tooltip. */
  const blockedReason = locked
    ? `Locked — the 2-day edit window for this exam has closed. Contact an admin to change it.`
    : hasInvalid
      ? `Fix ${invalidRows.length} invalid mark${invalidRows.length === 1 ? '' : 's'} first`
      : maxMarksError || examNameError
        || (enteredCount === 0 ? 'Enter at least one mark first' : 'Choose a class and subject first');

  /* ---- save: one atomic request for the whole class ---- */
  const handleSave = async () => {
    if (!canSave) return;
    setSaving(true);
    try {
      const payload = {
        classId,
        subject,
        examName: examName.trim(),
        date: date || undefined,
        maxMarks: maxValue,
        entries: roster
          .filter((r) => rowState[r.studentId]?.state === 'ok')
          .map((r) => ({ studentId: r.studentId, obtained: rowState[r.studentId].value })),
      };
      const res = await api.post(`/employees/${employeeId}/marks`, payload);
      const saved = res.data.data;
      setConfirmation({
        ...saved,
        examNames: [payload.examName],
        message: `Saved ${saved.saved} ${saved.subject} mark${saved.saved === 1 ? '' : 's'} for ${chipClassLabel || saved.classLabel}.`,
      });
      toast.success(`Saved ${saved.saved} ${saved.subject} mark${saved.saved === 1 ? '' : 's'}.`);
      // Re-read so the grid, the counter and the "already saved" list all show
      // what is actually in the database, not what was typed.
      await loadGrid(classId, subject, payload.examName);
    } catch (err) {
      const errors = err.response?.data?.errors;
      const lines = errorLines(errors);
      const message = err.response?.data?.message || 'Could not save marks.';
      toast.error(lines.length ? `${message} ${lines.join(' ')}` : message);
      // The server, not this page, decides the window is shut — it can close
      // while the form was open. Re-read the batch so the grid, the inputs and
      // the "already saved" badge all switch to the locked state at once,
      // instead of leaving a form that looks editable and is not.
      if (err.response?.data?.code === 'EDIT_LOCKED' && classId && subject) {
        await loadGrid(classId, subject, examName.trim());
      }
    } finally {
      setSaving(false);
    }
  };

  /* ---- bulk upload, scoped to the pair the page has already fixed ---- */
  const downloadTemplate = async (format) => {
    setDownloading(format);
    try {
      const params = new URLSearchParams({ classId, subject, format });
      const res = await api.get(`/employees/${employeeId}/marks/bulk-template?${params}`, { responseType: 'blob' });
      const url = URL.createObjectURL(res.data);
      const a = document.createElement('a');
      a.href = url;
      a.download = `marks_upload_template.${format}`;
      a.click();
      URL.revokeObjectURL(url);
    } catch {
      toast.error('Could not download the template.');
    } finally {
      setDownloading('');
    }
  };

  const handleBulk = async (file) => {
    setBulkErrors([]);
    if (!file) {
      setBulkErrors(['Choose a .csv or .xlsx file first.']);
      return;
    }
    setBulkBusy(true);
    try {
      const fd = new FormData();
      fd.append('file', file);
      // The class and the subject come from the selectors, never from the file.
      fd.append('classId', classId);
      fd.append('subject', subject);
      const res = await api.post(`/employees/${employeeId}/marks/bulk`, fd);
      const saved = res.data.data;
      toast.success(res.data.message || 'Marks saved.');
      setBulkOpen(false);
      /* An upload is a save, so it gets the same confirmation and the same
         2-day countdown — with the file's own exams named, since one file can
         carry several. The window it opens is stamped per exam by the server. */
      setConfirmation({
        ...saved,
        examNames: [...new Set((saved.rows || []).map((r) => r.examName))],
        message: `Saved ${saved.saved} ${saved.subject} mark${saved.saved === 1 ? '' : 's'} from the uploaded file for ${chipClassLabel || saved.classLabel}.`,
      });
      await loadGrid(classId, subject, examName.trim());
    } catch (err) {
      const lines = errorLines(err.response?.data?.errors);
      setBulkErrors(lines.length
        ? [err.response?.data?.message || 'Upload rejected.', ...lines]
        : [err.response?.data?.message || 'Bulk upload failed.']);
    } finally {
      setBulkBusy(false);
    }
  };

  /* An account with no linked employee record has no timetable to read, so the
     fetch never runs — resolve the spinner here rather than letting it spin
     against a request that was never made. */
  const isLoading = loading && Boolean(employeeId);
  if (isLoading) return <div className="loading-center"><div className="spinner" /></div>;

  // Either load — the assignments list or the roster grid — failing has to read
  // as a failure, not as "no assignments" or "no students".
  if (error) {
    return (
      <LoadErrorState
        title="Marks Entry"
        subtitle="Enter exam marks for the classes and subjects you teach"
        detail={error}
        onRetry={retry}
        icon={ClipboardList}
      />
    );
  }

  /* ---- no teaching assignments: an empty state, not an error ----
     Non-teaching staff (accountant, librarian) land here too, which is why the
     read endpoint returns an empty list rather than a 403. */
  if (assignments.length === 0) {
    return (
      <div className="page fade-in">
        <div className="page-header">
          <div className="page-title">Marks Entry</div>
          <div className="page-subtitle">Enter exam marks for the classes and subjects you teach</div>
        </div>
        <div className="empty-state">
          <ClipboardList size={40} />
          <div className="empty-state-title">No teaching assignments yet</div>
          <div>
            Marks entry is driven by your timetable. Once a period with your name
            is added to a class, that class and subject appear here.
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="page fade-in">
      <div className="page-header">
        <div className="page-title">Marks Entry</div>
        <div className="page-subtitle">
          Enter exam marks for the classes and subjects you teach · every mark you
          save is visible to the admin and the student · you can correct what you
          save for 2 days, after which only an admin can change it
        </div>
      </div>

      {/* ── The edit window of the batch on screen ──
          One line, always present while a SAVED batch is open, saying how long
          is left on it — and reading "Locked" once the window is shut. It is
          derived from the same `savedAt` and the same ticking clock as the
          inputs below, so it can never disagree with them, and it survives a
          reload because neither half of it is kept in component state.

          Deliberately NOT a live region: its text changes every tick, and
          announcing it every 30 seconds is noise. The one change worth
          announcing — the window closing — is repeated by the note above the
          roster, which does carry role="status". */}
      {remainingMs !== null && (
        <div className={`mk-window${locked ? ' locked' : ''}`}>
          {locked ? <ShieldAlert size={15} /> : <Clock size={15} />}
          <span className="mk-window-text">
            {locked
              ? `${EDIT_LOCKED_LABEL} · saved at ${shortStamp(savedAt)} — this exam is read-only for you`
              : `Saved at ${shortStamp(savedAt)} · editable for ${formatEditRemaining(remainingMs)}`}
          </span>
          <span className="mk-window-scope">{[activeClass?.label, subject].filter(Boolean).join(' · ')}</span>
        </div>
      )}

      {/* ── Your teaching assignments — read from the timetable, not a stored list ── */}
      <div className="section">
        <div className="section-title"><ClipboardList size={14} /> Your teaching assignments (from timetable)</div>
        <div className="card">
          <div className="mk-chips">
            {assignments.map((a) => {
              const active = a.classId === classId && a.subject === subject;
              return (
                <button
                  key={`${a.classId}::${a.subject}`}
                  type="button"
                  className={`mk-chip${active ? ' active' : ''}`}
                  aria-pressed={active}
                  title={`${a.periods} period${a.periods === 1 ? '' : 's'} a week · ${a.studentCount} students`}
                  onClick={() => selectPair(a.classId, a.subject)}
                >
                  {chipLabel(a)}
                </button>
              );
            })}
          </div>
          {activeAssignment && (
            <div className="text-sm text-muted" style={{ marginTop: 'var(--sp-md)' }}>
              {activeAssignment.periods} period{activeAssignment.periods === 1 ? '' : 's'} a week ·{' '}
              {activeAssignment.studentCount} student{activeAssignment.studentCount === 1 ? '' : 's'} in this class
            </div>
          )}
        </div>
      </div>

      {/* ── What to mark ── */}
      <div className="section">
        <div className="section-title"><Users size={14} /> Class, subject and exam</div>
        <div className="card">
          <div className="form-grid-2" style={{ marginBottom: 'var(--sp-md)' }}>
            <ClassSelect
              id="mk-class"
              value={classId}
              onChange={selectClass}
              choices={classChoices}
              placeholder="Choose a class…"
              disabled={saving || gridLoading}
            />

            {/* Subject: locked read-only when the timetable gives this teacher
                exactly one subject in the class, a dropdown when it gives more.
                Either way the value is the timetable's own spelling, so what is
                checked against the timetable is what gets stored. */}
            <div className="form-group">
              <label className="form-label" htmlFor="mk-subject">Subject</label>
              {subjectsForClass.length > 1 ? (
                <select
                  id="mk-subject"
                  className="form-input"
                  value={subject}
                  onChange={(e) => selectPair(classId, e.target.value)}
                  disabled={saving || gridLoading}
                  aria-label="Subject"
                >
                  {subjectsForClass.map((s) => <option key={s} value={s}>{s}</option>)}
                </select>
              ) : (
                /* An <output>, not a disabled select: it is labelable, so the
                   label is properly associated, and it means "a value this page
                   worked out", which is exactly what the subject is. */
                <output id="mk-subject" className="form-input mk-locked">
                  <Lock size={13} aria-hidden="true" />
                  <span>{subjectsForClass[0] || '—'}</span>
                </output>
              )}
            </div>
          </div>

          <div className="form-grid-3">
            <div className="form-group">
              <label className="form-label" htmlFor="mk-exam">Exam Name *</label>
              <input
                id="mk-exam"
                className="form-input"
                value={examName}
                onChange={(e) => setExamName(e.target.value)}
                placeholder="e.g. Unit Test 2"
                /* The exam's own name is part of what is locked, not just its
                   numbers: renaming it here would file this save under a
                   different exam, which is a way around the window rather than a
                   use of it. */
                disabled={readOnly}
                title={locked ? blockedReason : undefined}
              />
              {examNameError && !locked && <span className="mk-row-error">{examNameError}</span>}
            </div>
            <div className="form-group">
              <label className="form-label" htmlFor="mk-date">Exam Date</label>
              <input
                id="mk-date"
                type="date"
                className="form-input"
                value={date}
                onChange={(e) => setDate(e.target.value)}
                disabled={readOnly}
              />
            </div>
            <div className="form-group">
              <label className="form-label" htmlFor="mk-max">Max Marks *</label>
              <input
                id="mk-max"
                type="number"
                min="1"
                className="form-input"
                value={maxMarks}
                onChange={(e) => setMaxMarks(e.target.value)}
                disabled={readOnly}
              />
              {maxMarksError && !locked && <span className="mk-row-error">{maxMarksError}</span>}
            </div>
          </div>

          {renamed && (
            <div className="text-sm text-muted" style={{ marginTop: 'var(--sp-sm)' }}>
              These marks will be saved as <b>{examName.trim()}</b>, not {loadedExamName}.
            </div>
          )}
        </div>
      </div>

      {/* ── The roster: the whole class, in one screen ── */}
      <div className="section">
        {/* The live counter rides in the section title rather than its own row so
            it is always next to the roster it counts, and it inherits the same
            mono/uppercase treatment as every other section heading. */}
        <div className="section-title">
          <Users size={14} /> {activeClass ? activeClass.label : 'Class'} · {subject}
          <span className="mk-count">{enteredCount} of {roster.length} entered</span>
        </div>
        <div className="card" style={{ padding: 0 }}>
          {gridLoading ? (
            <div className="loading-center"><div className="spinner" /></div>
          ) : roster.length === 0 ? (
            <div className="text-muted" style={{ padding: 'var(--sp-lg)' }}>
              No students in this class yet.
            </div>
          ) : (
            <div className="table-wrapper mk-roster" style={{ border: 'none', borderRadius: 0, boxShadow: 'none' }}>
              <table>
                <thead>
                  <tr><th>Roll No</th><th>Name</th><th>Obtained</th></tr>
                </thead>
                <tbody>
                  {roster.map((r) => {
                    const state = rowState[r.studentId] || { state: 'empty' };
                    return (
                      <tr key={r.studentId}>
                        <td>{r.rollNumber || '—'}</td>
                        <td>{r.name}</td>
                        <td>
                          <div className="mk-cell">
                            <input
                              className={`form-input mk-input${state.state === 'invalid' && !locked ? ' mk-input--bad' : ''}`}
                              type="number"
                              min="0"
                              max={Number.isNaN(maxValue) ? undefined : maxValue}
                              value={entries[r.studentId] ?? ''}
                              onChange={(e) => setEntry(r.studentId, e.target.value)}
                              aria-label={`Obtained marks for ${r.name}`}
                              /* Read-only once the window closes — the marks stay
                                 on screen, this teacher just cannot change them. */
                              disabled={readOnly}
                              title={locked ? blockedReason : undefined}
                            />
                            {state.state === 'invalid' && !locked && (
                              <span className="mk-row-error">{state.reason}</span>
                            )}
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
        </div>

        {/* Why the fields above stopped accepting input, and what to do about it.
            Only shown when they actually are read-only, so it never explains a
            state the teacher is not in — and the one moment worth announcing,
            since it changes once and then stays. */}
        {locked && (
          <div className="mk-window locked" style={{ marginTop: 'var(--sp-md)' }} role="status">
            <ShieldAlert size={15} />
            <span className="mk-window-text">
              Locked — more than 2 days have passed. Contact an admin to change this.
            </span>
          </div>
        )}

        {hasInvalid && !locked && (
          <div className="login-error" style={{ marginTop: 'var(--sp-md)' }}>
            Fix {invalidRows.length} invalid mark{invalidRows.length === 1 ? '' : 's'}
            {maxValue >= 1 ? ` — obtained cannot be above ${maxValue} or below 0` : ''}. Nothing can be
            saved until they are corrected.
          </div>
        )}

        <div className="mk-actions">
          <button
            type="button"
            className="btn btn-primary"
            onClick={guard(handleSave)}
            disabled={!canSave || saving || cooling}
            title={canSave ? undefined : blockedReason}
          >
            <Save size={16} /> {saving ? 'Saving…' : 'Save Marks'}
          </button>
          <button
            type="button"
            className="btn btn-secondary"
            onClick={() => { setBulkErrors([]); setBulkOpen(true); }}
            disabled={!classId || !subject || saving}
            title={`Bulk upload ${subject} marks for ${activeClass?.label || 'the selected class'}`}
          >
            <FileSpreadsheet size={16} /> Bulk Upload
          </button>
          <span className="text-sm text-muted">
            The whole class saves in one go — and a blank cell stays unrecorded rather than
            being stored as a zero.
            {!locked && ' Saved marks stay editable for 2 days; after that only an admin can change them.'}
          </span>
        </div>
      </div>

      {/* ── What this teacher has already saved here ── */}
      <div className="section">
        <div className="section-title"><History size={14} /> Already saved · {activeClass ? activeClass.label : ''} · {subject}</div>
        <div className="card">
          {!grid || grid.exams.length === 0 ? (
            <div className="text-muted">
              Nothing saved yet for this class and subject. Enter marks in the grid above, or
              bulk upload a spreadsheet — anything you save here shows up in this list and
              can be re-loaded to correct.
            </div>
          ) : (
            <div className="mk-saved-list">
              {grid.exams.map((ex) => {
                // Each card carries its own batch's window, counted down against
                // the same clock as the open one — so the list stays honest while
                // the page sits open, and reopening the page shows the same
                // numbers rather than restarting them.
                const exLeft = editRemainingMs(ex.savedAt, now);
                const exLocked = exLeft === 0;
                return (
                  <button
                    key={ex.examId}
                    type="button"
                    className="mk-saved-item"
                    onClick={() => loadGrid(classId, subject, ex.examName)}
                    title={exLocked
                      ? `Open ${ex.examName} — read-only, the 2-day edit window has closed`
                      : `Load ${ex.examName} into the grid to correct it`}
                  >
                    <div className="mk-saved-name">{ex.examName}</div>
                    <div className="text-sm text-muted">{ex.date}</div>
                    <div className="mk-saved-stats">
                      <span className="badge badge-muted">{ex.saved} entered</span>
                      {ex.average !== null && <span className="badge badge-info">avg {ex.average}</span>}
                      {ex.top !== null && <span className="badge badge-success">top {ex.top}</span>}
                      {/* Only for a batch this teacher actually saved: one only the
                          office ever entered has no teacher window to count down. */}
                      {exLeft !== null && (
                        <span className={`badge ${exLocked ? 'badge-warning' : 'badge-info'}`}>
                          {exLocked ? EDIT_LOCKED_LABEL : `${shortEditRemaining(exLeft)} left to edit`}
                        </span>
                      )}
                      {ex.updatedBy
                        ? <span className="badge badge-warning">last changed by {ex.updatedBy}</span>
                        : ex.enteredBy && <span className="badge badge-primary">entered by {ex.enteredBy}</span>}
                    </div>
                  </button>
                );
              })}
            </div>
          )}
        </div>
      </div>

      {/* ── Save confirmation ── */}
      {confirmation && (
        <Modal
          title="Marks saved"
          onClose={() => setConfirmation(null)}
          footer={(
            <button className="btn btn-primary" onClick={() => setConfirmation(null)}>Done</button>
          )}
        >
          <div className="mk-confirm">
            <ClipboardList size={34} />
            <div className="mk-confirm-msg">{confirmation.message}</div>
            <ul className="mk-confirm-list">
              {confirmation.examNames?.length > 0 && (
                <li>
                  <b>{confirmation.examNames.join(', ')}</b>
                  {confirmation.date ? ` · ${confirmation.date}` : ''}
                </li>
              )}
              {confirmation.maxMarks !== undefined && (
                <li>{confirmation.subject} · out of {confirmation.maxMarks}</li>
              )}
              {confirmation.notEntered > 0 && (
                <li>{confirmation.notEntered} student{confirmation.notEntered === 1 ? '' : 's'} left blank — not saved, and not recorded as zero</li>
              )}
              {/* The window, counted from the instant the server stamped — not from
                  a timer started when this dialog opened, which is why the number
                  here and the badge on the card below always agree. */}
              {justSavedMs !== null && (
                <li className="mk-confirm-window">
                  <Clock size={13} aria-hidden="true" />
                  Editable for {formatEditRemaining(justSavedMs)}
                  {confirmation.editableUntil ? `, until ${shortStamp(confirmation.editableUntil)}` : ''}.
                  {' '}After that only an admin can change these marks.
                </li>
              )}
              <li className="text-muted">Recorded under your name, visible to the admin immediately.</li>
            </ul>
          </div>
        </Modal>
      )}

      {/* ── Bulk upload — scoped to the class and subject already chosen ── */}
      {bulkOpen && (
        <Modal
          wide
          title={`Bulk Upload — ${activeClass?.label || ''} · ${subject}`}
          onClose={() => setBulkOpen(false)}
          footer={<button className="btn btn-secondary" onClick={() => setBulkOpen(false)}>Close</button>}
        >
          {bulkErrors.length > 0 && (
            <div className="login-error" style={{ marginBottom: 'var(--sp-md)' }}>
              <ul style={{ margin: 0, paddingLeft: '1.1rem' }}>
                {bulkErrors.map((line, i) => <li key={i}>{line}</li>)}
              </ul>
            </div>
          )}

          <div className="text-sm" style={{ marginBottom: 'var(--sp-md)' }}>
            Uploading marks for <b>{activeClass?.label}</b> in <b>{subject}</b> — your own subject in
            your own class. Students are matched by RollNumber, and a roll number from any other
            class is rejected.
          </div>

          <div className="form-group">
            <label className="form-label">Upload a spreadsheet (.csv or .xlsx)</label>
            <input
              type="file"
              className="form-input"
              accept=".csv,.xlsx"
              disabled={bulkBusy}
              onChange={(e) => {
                const file = e.target.files?.[0];
                e.target.value = ''; // allow re-choosing the same file after a failed attempt
                if (file) handleBulk(file);
              }}
              aria-label="Bulk upload marks file"
            />
          </div>

          <div className="mk-downloads">
            {['xlsx', 'csv'].map((format) => (
              <button
                key={format}
                type="button"
                className="btn btn-secondary btn-sm"
                onClick={() => downloadTemplate(format)}
                disabled={Boolean(downloading)}
                aria-label={`Download the marks upload template as ${format.toUpperCase()}`}
              >
                <Download size={14} />
                {downloading === format ? 'Preparing…' : `Template (.${format})`}
              </button>
            ))}
          </div>

          <div className="text-sm text-muted" style={{ marginTop: 'var(--sp-md)' }}>
            Header row required, in this order: <b>{BULK_COLUMNS.join(', ')}</b>.<br />
            There are <b>no Class and no Subject columns</b> — both come from the selectors on this
            page, so every row is saved for {activeClass?.label} in {subject}. One row per student;
            up to 200 rows per file, validated together: if any row is invalid nothing is saved and
            the failing rows and columns are listed above. Re-uploading the same exam corrects the
            existing marks instead of adding a second copy.<br />
            An upload counts as a save, so it obeys the same <b>2-day edit window</b>: a file naming
            an exam whose window has already closed is rejected whole, exactly as an invalid row
            would be. Contact an admin for that change.
          </div>
        </Modal>
      )}
    </div>
  );
}
